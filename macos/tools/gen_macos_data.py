#!/usr/bin/env python3
"""Regenerate the macOS editor colours: macos/Sources/Markite/Palette.swift (never hand-edit it).

Same source as gnome/tools/gen_gnome_data.py: KDE syntax-highlighting theme files (same TAG, SLUGS and Markdown item
table, read from that script so the three editors cannot drift). Needs network, same as the GNOME generator:
    python3 macos/tools/gen_macos_data.py
Output is pure Swift with no imports (colours are 0xRRGGBB UInt32; alpha, where a theme has it, is a separate Double),
so it type-checks anywhere. Lookup: `editorPalette(named: "Breeze Dark")` with the names core::options::theme_name
returns. Markdown syntax colours are in `EditorPalette.tokens`, keyed by the item names of the GNOME generator's MD
table ("header", "emphasis", "code-span", ...).
"""
import ast
import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GNOME = (ROOT / "gnome/tools/gen_gnome_data.py").read_text(encoding="utf-8")


def gnome_const(name):
    """A top-level literal assignment of the GNOME generator (it runs on import, so it cannot be imported)."""
    for node in ast.parse(GNOME).body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == name:
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in gen_gnome_data.py")


TAG, SLUGS, MD = gnome_const("TAG"), gnome_const("SLUGS"), gnome_const("MD")
URL = gnome_const("URL")
# Display names, as core::options::theme_name returns them, in the order of SLUGS.
NAMES = {"breeze-light": "Breeze Light", "breeze-dark": "Breeze Dark", "atom-one-light": "Atom One Light",
         "atom-one-dark": "Atom One Dark", "catppuccin-latte": "Catppuccin Latte",
         "catppuccin-mocha": "Catppuccin Mocha", "github-light": "GitHub Light", "github-dark": "GitHub Dark",
         "solarized-light": "Solarized Light", "solarized-dark": "Solarized Dark"}
DARK = {"breeze-dark", "atom-one-dark", "catppuccin-mocha", "github-dark", "solarized-dark"}
GENERATED = f"Generated by macos/tools/gen_macos_data.py from KDE syntax-highlighting {TAG} (data/themes, MIT). Do not edit."


def fetch(slug):
    with urllib.request.urlopen(URL.format(tag=TAG, slug=slug), timeout=30) as resp:
        return json.load(resp)


def rgb(c):
    """Qt `#RRGGBB` or `#AARRGGBB` -> (0xRRGGBB, alpha 0..1)."""
    if len(c) == 9:
        return int(c[3:9], 16), round(int(c[1:3], 16) / 255, 3)
    return int(c[1:7], 16), 1.0


def hexl(v):
    return f"0x{v:06X}"


def token(md, ts, item):
    name, style, base = MD[item]
    t = md.get(name, {})
    flags = set(base)
    for f, k in (("b", "bold"), ("i", "italic"), ("u", "underline")):
        if k in t:
            (flags.add if t[k] else flags.discard)(f)
    c = rgb(t.get("text-color") or ts[style]["text-color"])[0]
    b = lambda f: "true" if f in flags else "false"
    return f'"{item}": SyntaxStyle(color: {hexl(c)}, bold: {b("b")}, italic: {b("i")}, underline: {b("u")})'


def palette(slug, d):
    ts, ec = d["text-styles"], d["editor-colors"]
    md = d.get("custom-styles", {}).get("Markdown", {})
    link = md.get("Link", {}).get("text-color") or ts["Others"]["text-color"]
    sel, sel_a = rgb(ec["TextSelection"])
    cbg, cbg_a = rgb(ec["CurrentLine"])
    item = lambda i: rgb(md.get(MD[i][0], {}).get("text-color") or ts[MD[i][1]]["text-color"])[0]
    toks = ",\n            ".join(token(md, ts, i) for i in MD)
    return f"""    EditorPalette(
        name: "{NAMES[slug]}", isDark: {"true" if slug in DARK else "false"},
        background: {hexl(rgb(ec["BackgroundColor"])[0])}, text: {hexl(rgb(ts["Normal"]["text-color"])[0])},
        selection: {hexl(sel)}, selectionAlpha: {sel_a:g},
        lineNumber: {hexl(rgb(ec["LineNumbers"])[0])}, currentLine: {hexl(cbg)}, currentLineAlpha: {cbg_a:g},
        heading: {hexl(item("header"))}, code: {hexl(item("code"))}, link: {hexl(rgb(link)[0])},
        quote: {hexl(item("quote-text"))},
        tokens: [
            {toks},
        ]
    )"""


body = ",\n".join(palette(s, fetch(s)) for s in SLUGS)
out = ROOT / "macos/Sources/Markite/Palette.swift"
out.write_text(f"""// {GENERATED}

/// Colours are 0xRRGGBB. `selection` and `currentLine` also carry an alpha (1 when the theme has none); the preview's
/// code background is `currentLine`.
struct SyntaxStyle {{
    let color: UInt32
    let bold: Bool
    let italic: Bool
    let underline: Bool
}}

struct EditorPalette {{
    let name: String
    let isDark: Bool
    let background: UInt32
    let text: UInt32
    let selection: UInt32
    let selectionAlpha: Double
    let lineNumber: UInt32
    let currentLine: UInt32
    let currentLineAlpha: Double
    let heading: UInt32
    let code: UInt32
    let link: UInt32
    let quote: UInt32
    /// Markdown source colours keyed by item ("header", "emphasis", "strong-emphasis", "code-span", "list-marker", ...).
    let tokens: [String: SyntaxStyle]
}}

let editorPalettes: [EditorPalette] = [
{body},
]

/// The palette for a theme name as `theme_name` in the core returns it ("Breeze Dark"); nil when unknown.
func editorPalette(named name: String) -> EditorPalette? {{
    editorPalettes.first {{ $0.name == name }}
}}
""", encoding="utf-8")
print("wrote", out)
